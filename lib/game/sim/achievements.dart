import 'environment.dart';
import 'modifier.dart';

/// Game Center achievements. The [id] is the App Store Connect Achievement ID
/// as well as the key the unlock is remembered under on the device.
///
/// The list in `store/APP_STORE.md` → *Game Center* (title, points,
/// description) is what gets typed into App Store Connect; keep both in step.
enum AchievementId {
  firstRun('puff.ach.first_run'),
  comboX4('puff.ach.combo_x4'),
  combo40('puff.ach.combo_40'),
  perfectRelease('puff.ach.perfect_release'),
  heat3('puff.ach.heat_3'),
  overdrive('puff.ach.overdrive'),
  untouchable('puff.ach.untouchable'),
  shatter50('puff.ach.shatter_50'),
  allEnvironments('puff.ach.all_environments'),
  allModifiers('puff.ach.all_modifiers'),
  allPalettes('puff.ach.all_palettes'),
  runs10('puff.ach.runs_10'),
  runs50('puff.ach.runs_50'),
  weekly('puff.ach.weekly');

  const AchievementId(this.id);

  final String id;

  /// Play Games IDs are generated by Play Console; empty until the
  /// achievements exist there, and then skipped on Android.
  String get androidId => '';
}

/// What one finished run did, gathered while it was played.
class RunRecord {
  const RunRecord({
    required this.environment,
    required this.modifier,
    required this.palette,
    required this.score,
    required this.bestCombo,
    required this.maxTier,
    required this.seconds,
    required this.fractures,
    required this.perfectReleases,
    required this.firstCoreHitAt,
    this.weekly = false,
  });

  final EnvironmentKind environment;
  final ModifierKind modifier;
  final String palette;
  final int score;
  final int bestCombo;
  final int maxTier;
  final double seconds;
  final int fractures;

  /// Releases at full charge that did not overpressure.
  final int perfectReleases;

  /// Seconds into the run when the core was first hit; null if never.
  final double? firstCoreHitAt;
  final bool weekly;
}

/// Lifetime progress the cross-run achievements count from.
class AchievementProgress {
  AchievementProgress({
    this.runs = 0,
    Set<String>? environments,
    Set<String>? modifiers,
    Set<String>? palettes,
    Set<String>? unlocked,
  }) : environments = environments ?? {},
       modifiers = modifiers ?? {},
       palettes = palettes ?? {},
       unlocked = unlocked ?? {};

  int runs;
  final Set<String> environments;
  final Set<String> modifiers;
  final Set<String> palettes;

  /// Achievement IDs already unlocked on this device.
  final Set<String> unlocked;
}

class AchievementRules {
  const AchievementRules({
    required this.comboStep,
    required this.paletteCount,
  });

  /// Multiplier gained per combo hit, so "x4" can be stated as a combo count.
  final double comboStep;
  final int paletteCount;

  static const perfectCharge = 0.95;
  static const untouchableSeconds = 60.0;

  int get comboForX4 => (3 / comboStep).ceil();

  /// Whether a release counts as perfect: nearly full, not overpressured.
  static bool isPerfect(double energy, {required bool overpressured}) =>
      !overpressured && energy >= perfectCharge;

  /// Folds [run] into [progress] and returns the achievements it newly
  /// unlocks, in declaration order. [progress] is updated in place, including
  /// [AchievementProgress.unlocked].
  List<AchievementId> record(RunRecord run, AchievementProgress progress) {
    progress.runs += 1;
    progress.environments.add(run.environment.name);
    progress.modifiers.add(run.modifier.name);
    progress.palettes.add(run.palette);

    final earned = <AchievementId>{
      AchievementId.firstRun,
      if (run.bestCombo >= comboForX4) AchievementId.comboX4,
      if (run.bestCombo >= 40) AchievementId.combo40,
      if (run.perfectReleases > 0) AchievementId.perfectRelease,
      if (run.maxTier >= 3) AchievementId.heat3,
      if (run.maxTier >= 4) AchievementId.overdrive,
      if (run.seconds >= untouchableSeconds &&
          (run.firstCoreHitAt == null || run.firstCoreHitAt! >= untouchableSeconds))
        AchievementId.untouchable,
      if (run.fractures >= 50) AchievementId.shatter50,
      if (progress.environments.length >= EnvironmentKind.values.length)
        AchievementId.allEnvironments,
      if (progress.modifiers.length >= ModifierKind.values.length)
        AchievementId.allModifiers,
      if (progress.palettes.length >= paletteCount) AchievementId.allPalettes,
      if (progress.runs >= 10) AchievementId.runs10,
      if (progress.runs >= 50) AchievementId.runs50,
      if (run.weekly) AchievementId.weekly,
    };
    final fresh = [
      for (final a in AchievementId.values)
        if (earned.contains(a) && !progress.unlocked.contains(a.id)) a,
    ];
    progress.unlocked.addAll(fresh.map((a) => a.id));
    return fresh;
  }
}
