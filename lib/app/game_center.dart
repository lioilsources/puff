import 'dart:async';

import 'package:flutter/foundation.dart';
import 'package:games_services/games_services.dart';

import '../game/sim/environment.dart';

/// Leaderboards, one per environment: Game Center on iOS and macOS, Play Games
/// Services on Android.
///
/// Every call here is best-effort. The player is free to decline the sign-in,
/// an Android build may ship before its boards exist, and a submission can fail
/// with no network. None of that is worth interrupting a run over, so failures
/// are swallowed and [available] simply stays false — the local high scores
/// carry on alone.
class GameCenter extends ChangeNotifier {
  bool _available = false;
  StreamSubscription<PlayerData?>? _player;

  /// True once the player is signed in and submissions can be made.
  bool get available => _available;

  /// Whether the UI should show its leaderboard entry point.
  ///
  /// Game Center is signed in to from iOS Settings, so there the button only
  /// makes sense once that has happened. Play Games has no such place: the
  /// button is the sign-in, and [show] prompts when it is tapped signed out.
  bool get offered => _available || _android;

  /// Board IDs as created in App Store Connect. Scores differ by an order of
  /// magnitude between environments, so they get a board each rather than one
  /// table the easiest environment would own.
  static String leaderboardId(EnvironmentKind env) => 'puff.${env.name}';

  /// Board IDs as generated by Play Console (Play Games Services →
  /// Leaderboards; they look like `CgkI…EAIQAQ`). Google picks them, so they
  /// cannot follow the `puff.<env>` scheme. While any of them is empty the
  /// Android build behaves as if there were no leaderboards at all.
  static const _androidLeaderboardIds = <EnvironmentKind, String>{
    EnvironmentKind.vacuum: '',
    EnvironmentKind.air: '',
    EnvironmentKind.water: '',
    EnvironmentKind.plasma: '',
  };

  static String androidLeaderboardId(EnvironmentKind env) =>
      _androidLeaderboardIds[env] ?? '';

  static bool get _android =>
      defaultTargetPlatform == TargetPlatform.android &&
      EnvironmentKind.values.every((e) => androidLeaderboardId(e).isNotEmpty);

  static bool get _supported =>
      defaultTargetPlatform == TargetPlatform.iOS ||
      defaultTargetPlatform == TargetPlatform.macOS ||
      _android;

  /// Signs in silently at startup. Game Center shows its own banner.
  ///
  /// The player stream, not the result of [GameAuth.signIn], is what decides
  /// [available]: authentication can complete well after the call returns, and
  /// the player may sign in from iOS Settings while the game is running.
  ///
  /// On Android only the stream is opened. Play Games attempts its own sign-in
  /// at launch and the stream reports the outcome; calling [GameAuth.signIn]
  /// there raises a dialog, which a player who declined once would then get on
  /// every launch. [show] asks instead, when they tap the button.
  Future<void> signIn() async {
    if (!_supported) {
      return;
    }
    _player ??= GameAuth.player.listen(
      (player) => _setAvailable(player != null),
      onError: (Object error) {
        debugPrint('Puff: Game Center player stream failed: $error');
        _setAvailable(false);
      },
    );
    if (_android) {
      return;
    }
    await _prompt();
  }

  Future<void> _prompt() async {
    try {
      await GameAuth.signIn();
    } catch (error) {
      debugPrint('Puff: Game Center sign-in failed: $error');
    }
  }

  void _setAvailable(bool value) {
    if (value == _available) {
      return;
    }
    _available = value;
    notifyListeners();
  }

  @override
  void dispose() {
    _player?.cancel();
    super.dispose();
  }

  /// Posts a finished run. Game Center keeps the best of what it is sent, so
  /// every run goes up, not only local bests.
  Future<void> submit(EnvironmentKind env, int score) async {
    if (!_available) {
      return;
    }
    try {
      await Leaderboards.submitScore(
        score: Score(
          iOSLeaderboardID: leaderboardId(env),
          androidLeaderboardID: androidLeaderboardId(env),
          value: score,
        ),
      );
    } catch (error) {
      debugPrint('Puff: Game Center submit failed: $error');
    }
  }

  /// Opens the system leaderboard for [env].
  Future<void> show(EnvironmentKind env) async {
    if (!_available && _android) {
      await _prompt();
      // The stream flips [available] too, but not before the board has to open.
      _setAvailable(await GameAuth.isSignedIn);
    }
    if (!_available) {
      return;
    }
    try {
      await Leaderboards.showLeaderboards(
        iOSLeaderboardID: leaderboardId(env),
        androidLeaderboardID: androidLeaderboardId(env),
      );
    } catch (error) {
      debugPrint('Puff: Game Center leaderboard failed to open: $error');
    }
  }
}
